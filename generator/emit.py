# --- Modules ------------------------------------------------------------------------


def _is_simple_typedef(d: Typedef) -> bool:
    # Typedefs that refer to no other definition can come first in a module.
    return isinstance(d.type, Primitive | OpaqueFixed | OpaqueVar | String)


def _names_used(body: str) -> frozenset[str]:
    """The names that the code of a module refers to, which decide its imports.

    The code is parsed rather than searched: its docstrings and comments quote the XDR
    source, where a word such as `Sequence` is not a use of the name.
    """
    return frozenset(
        node.id for node in ast.walk(ast.parse(body)) if isinstance(node, ast.Name)
    )


class Generator(_Emitter):
    """Turns a model into the source of every module of the package."""

    def __init__(
        self, model: Model, protocol: int, rules: sep51.Rules = sep51.RULES
    ) -> None:
        super().__init__(model, rules)
        self.protocol = protocol

    def _ordered_typedefs(self, typedefs: list[Typedef]) -> list[Typedef]:
        # An alias is evaluated at import time, so the aliases it refers to come first.
        by_name = {d.name: d for d in typedefs}
        done: dict[str, Typedef] = {}

        def visit(d: Typedef) -> None:
            if d.name in done:
                return
            for ref in _references(d):
                if ref in by_name:
                    visit(by_name[ref])
            done[d.name] = d

        for d in typedefs:
            visit(d)
        return list(done.values())

    def _typedef_blocks(self, typedefs: list[Typedef]) -> list[list[str]]:
        """The typedefs in order: a class by itself, aliases on consecutive lines."""
        blocks: list[list[str]] = []
        aliases: list[str] = []
        for d in typedefs:
            lines = self.typedef(d)
            if len(lines) == 1:
                aliases += lines
                continue
            if aliases:
                blocks.append(aliases)
                aliases = []
            blocks.append(lines)
        if aliases:
            blocks.append(aliases)
        return blocks

    def module(self, module: _Module) -> str:
        """The source of one module."""
        self.ctx.current = module
        consts = [d for d in module.definitions if isinstance(d, Const)]
        enums = [d for d in module.definitions if isinstance(d, Enum)]
        typedefs = [d for d in module.definitions if isinstance(d, Typedef)]
        simple = [d for d in typedefs if _is_simple_typedef(d)]
        composite = self._ordered_typedefs(
            [d for d in typedefs if not _is_simple_typedef(d)]
        )
        classes = [d for d in module.definitions if isinstance(d, Struct | Union)]
        blocks: list[list[str]] = []
        if consts:
            blocks.append([line for d in consts for line in self.const(d)])
        blocks += [self.enum(d) for d in enums]
        blocks += self._typedef_blocks(simple)
        for d in classes:
            blocks.append(self.struct(d) if isinstance(d, Struct) else self.union(d))
        blocks += self._typedef_blocks(composite)
        body = "\n\n\n".join("\n".join(b) for b in blocks)
        public = sorted(_public_name(d) for d in module.definitions)
        exports = "\n".join(f"    {n!r}," for n in public)
        return "\n".join(
            [
                HEADER.rstrip(),
                f'"""The types of ``{module.xdr_file.rsplit("/", 1)[-1]}``.',
                "",
                "Import them from `stellar_xdr`. This module is private: it follows",
                "the layout of the `.x` files, and a definition can move to another",
                "file between releases.",
                '"""',
                "",
                "# The code uses private parts of the runtime and of other modules.",
                "# pyright: reportPrivateUsage=false",
                "",
                "from __future__ import annotations",
                "",
                *self._imports(module, body),
                "",
                "",
                body,
                "",
                "",
                f"__all__ = [\n{exports}\n]",
                "",
            ]
        )

    def _imports(self, module: _Module, body: str) -> list[str]:
        used = _names_used(body)
        lines: list[str] = []
        if "builtins" in used:
            lines.append("import builtins")
        if "strkey" in used:
            lines.append("import stellar_strkey as strkey")
        if "Sequence" in used:
            lines.append("from collections.abc import Sequence")
        used_typing = sorted(used.intersection(TYPING_NAMES))
        if used_typing:
            lines.append(f"from typing import {', '.join(used_typing)}")
        lines.append("")
        runtime = sorted(used.intersection(RUNTIME_NAMES))
        lines.append(f"from ._runtime import {', '.join(runtime)}")
        for other in sorted(module.imports):
            imported = ", ".join(sorted(module.imports[other]))
            lines.append(f"from .{other} import {imported}")
        return lines

    def package_init(self) -> str:
        """The source of the package's `__init__.py`, which re-exports every name."""
        lines = [
            HEADER.rstrip(),
            '"""Strict, fully typed encoding and decoding of Stellar XDR.',
            "",
            "Every type is importable from here, and this is the only place to import",
            "one from: the modules that define them are private.",
            '"""',
            "",
            "from typing import Final",
            "",
            "from ._runtime import (",
            *(f"    {n}," for n in sorted(PUBLIC_RUNTIME_NAMES)),
            ")",
        ]
        exported = [*PUBLIC_RUNTIME_NAMES, "PROTOCOL_VERSION"]
        for module in self.modules.values():
            public = sorted(_public_name(d) for d in module.definitions)
            exported += public
            lines += [
                f"from .{module.name} import (",
                *(f"    {n}," for n in public),
                ")",
            ]
        lines += [
            "",
            f"PROTOCOL_VERSION: Final = {self.protocol}",
            '"""The Stellar protocol version of the XDR definitions in this release.',
            "",
            "The package's own version follows semantic versioning of its API, so it",
            "doesn't say which protocol it supports; this does.",
            '"""',
            "",
            "__all__ = [",
            *(f"    {n!r}," for n in sorted(exported)),
            "]",
            "",
        ]
        return "\n".join(lines)

    def arm_names(self) -> str:
        """`generator/arm_names.txt`: the arm classes of every union, one line each.

        The generated code is too long to review by eye, so a change to the names users
        see, such as an ugly name for a new union, would be easy to miss. In this short
        file, every such change shows up in the diff of an update.
        """
        lines = [
            "# Generated by `python -m generator`: the arm classes of every union. A",
            "# change here is a change to the API; see `arm_class_name` in names.py.",
        ]
        for d in self.model.definitions:
            if isinstance(d, Union):
                arms = [
                    names.arm_class_name(self.model, d, c.value, c.name)
                    for a in d.arms
                    for c in a.cases
                ]
                lines.append(f"{names.type_name(d.name)}: {', '.join(arms)}")
        return "\n".join(lines) + "\n"

    def sources(self) -> dict[str, str]:
        """Every generated file of the package, by path relative to the package."""
        result = {f"{m.name}.py": self.module(m) for m in self.modules.values()}
        result["__init__.py"] = self.package_init()
        return result


# --- Hypothesis strategies for the tests ----------------------------------------------

_INTEGER_RANGES: Final = {
    "int": ("-(2**31)", "2**31 - 1"),
    "unsigned_int": ("0", "2**32 - 1"),
    "hyper": ("-(2**63)", "2**63 - 1"),
    "unsigned_hyper": ("0", "2**64 - 1"),
}

# Kept small so that examples stay fast; the limits themselves are tested separately.
_MAX_TEST_BYTES: Final = 40
_MAX_TEST_ITEMS: Final = 3


# Fields whose random values need a length of their own: (struct, field) to the fewest
# bytes. A strkey, and so SEP-51, needs a signed payload of at least one byte.
_MIN_TEST_BYTES: Final = {("SignerKeyEd25519SignedPayload", "payload"): 1}


class StrategyGenerator:
    """Emits `tests/strategies.py`: a Hypothesis strategy for every type."""

    def __init__(self, model: Model) -> None:
        self.model = model

    def _strategy(self, t: TypeRef, min_bytes: int = 0) -> str:
        if isinstance(t, Primitive):
            if t.kind == "bool":
                return "st.booleans()"
            low, high = _INTEGER_RANGES[t.kind]
            return f"st.integers({low}, {high})"
        if isinstance(t, Ref):
            d = self.model.get(t.name)
            if isinstance(d, Typedef):
                return self._strategy(d.type, min_bytes)
            return f"ref({names.type_name(t.name)!r})"
        if isinstance(t, OpaqueFixed):
            return f"st.binary(min_size={t.size}, max_size={t.size})"
        if isinstance(t, OpaqueVar | String):
            limit = min(t.max_size or _MAX_TEST_BYTES, _MAX_TEST_BYTES)
            if min_bytes:
                return f"st.binary(min_size={min_bytes}, max_size={limit})"
            return f"st.binary(max_size={limit})"
        if isinstance(t, VarArray):
            limit = min(
                _MAX_TEST_ITEMS if t.max_count is None else t.max_count, _MAX_TEST_ITEMS
            )
            return f"st.lists({self._strategy(t.element)}, max_size={limit}).map(tuple)"
        if isinstance(t, Array):
            n = t.count
            element = self._strategy(t.element)
            return f"st.lists({element}, min_size={n}, max_size={n}).map(tuple)"
        return f"st.none() | {self._strategy(t.element)}"

    def source(self) -> str:
        """The source of the strategies module."""
        lines = [
            HEADER.rstrip(),
            '"""A Hypothesis strategy for every type, keyed by its Python name."""',
            "",
            "from typing import Any",
            "",
            "from hypothesis import strategies as st",
            "",
            "import stellar_xdr as xdr",
            "",
            "STRATEGIES: dict[str, st.SearchStrategy[Any]] = {}",
            '"""Every struct, enum, union and typedef that is a class."""',
            "",
            "ARMS: dict[str, tuple[str, st.SearchStrategy[Any]]] = {}",
            '"""Every arm of every union, such as "SCVal.U32", with its union."""',
            "",
            "DISCRIMINANTS: dict[str, frozenset[int]] = {}",
            '"""The discriminants that select an arm, for every union."""',
            "",
            "",
            "def ref(name: str) -> st.SearchStrategy[Any]:",
            '    """The strategy of a definition, looked up when it is first used."""',
            "    return st.deferred(lambda: STRATEGIES[name])",
            "",
            "",
        ]
        for d in self.model.definitions:
            name = names.type_name(d.name)
            if isinstance(d, Struct):
                fields = [
                    self._strategy(f.type, _MIN_TEST_BYTES.get((d.name, f.name), 0))
                    for f in d.fields
                ]
                args = "".join(f", {strategy}" for strategy in fields)
                lines.append(f"STRATEGIES[{name!r}] = st.builds(xdr.{name}{args})")
            elif isinstance(d, Enum):
                lines.append(f"STRATEGIES[{name!r}] = st.sampled_from(xdr.{name})")
            elif isinstance(d, Typedef):
                # An alias has no class of its own to test: its type has.
                if typedef_base(self.model, d) is not None:
                    plain = self._strategy(d.type)
                    lines.append(
                        f"STRATEGIES[{name!r}] = st.builds(xdr.{name}, {plain})"
                    )
            elif isinstance(d, Union):
                arms: list[str] = []
                for arm in d.arms:
                    payload = (
                        "" if arm.type is None else f", {self._strategy(arm.type)}"
                    )
                    for case in arm.cases:
                        arm_name = names.arm_class_name(
                            self.model, d, case.value, case.name
                        )
                        strategy = f"st.builds(xdr.{name}.{arm_name}{payload})"
                        arms.append(strategy)
                        lines.append(
                            f"ARMS['{name}.{arm_name}'] = ({name!r}, {strategy})"
                        )
                lines.append(f"STRATEGIES[{name!r}] = st.one_of({', '.join(arms)})")
                values = sorted(c.value for a in d.arms for c in a.cases)
                lines.append(f"DISCRIMINANTS[{name!r}] = frozenset({values})")
        lines.append("")
        return "\n".join(lines)
