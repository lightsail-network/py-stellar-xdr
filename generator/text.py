"""Small helpers for writing source text."""

from typing import Final

HEADER: Final = "# Generated by `python -m generator` from xdr/xdr.json. Do not edit.\n"


def indent(lines: list[str], levels: int = 1) -> list[str]:
    """Indent every line that isn't empty."""
    pad = "    " * levels
    return [pad + line if line else line for line in lines]


def tuple_display(items: list[str]) -> str:
    """A tuple display, with a trailing comma only where one item needs it.

    After a trailing comma, ruff puts every item on a line of its own.
    """
    return f"({items[0]},)" if len(items) == 1 else f"({', '.join(items)})"


def docstring(lines: list[str]) -> list[str]:
    """The lines of a docstring that holds the given text."""
    text = "\n".join(lines).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    body = text.split("\n")
    if len(body) == 1:
        return [f'"""{body[0]}"""']
    return [f'"""{body[0]}', *body[1:], '"""']


def source_block(source: str) -> list[str]:
    """The XDR source of a definition, as a code block for its docstring."""
    return ["", "```xdr", *source.expandtabs(4).splitlines(), "```"]
